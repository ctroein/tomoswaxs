"""Render a static overview of the synthetic fixtures; this is not the GUI."""
from pathlib import Path
import numpy as np
import vtk
from vtk.util.numpy_support import numpy_to_vtk, vtk_to_numpy
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from synthetic_demo import generate, scattering

base = Path(__file__).parent
data_dir = base.parent/'data'
volume, spacing, origin = generate(data_dir)
image = vtk.vtkImageData()
image.SetDimensions(*volume.shape[::-1])
image.SetSpacing(spacing, spacing, spacing)
image.SetOrigin(*origin)
image.GetPointData().SetScalars(numpy_to_vtk(volume.ravel(), deep=True))
mapper = vtk.vtkSmartVolumeMapper()
mapper.SetInputData(image)
colors = vtk.vtkColorTransferFunction()
for scalar, color in [(0, (.05,.08,.12)), (10000, (.35,.45,.60)),
                      (24000, (.80,.65,.38)), (50000, (1.,.92,.72))]:
    colors.AddRGBPoint(scalar, *color)
opacity = vtk.vtkPiecewiseFunction()
for value, alpha in [(0,0), (9000,0), (18000,.025), (35000,.12), (65535,.4)]:
    opacity.AddPoint(value, alpha)
prop = vtk.vtkVolumeProperty()
prop.SetColor(colors)
prop.SetScalarOpacity(opacity)
prop.SetScalarOpacityUnitDistance(spacing)
prop.SetAmbient(.4)
prop.SetDiffuse(.6)
prop.SetInterpolationTypeToLinear()
prop.ShadeOn()
actor = vtk.vtkVolume()
actor.SetMapper(mapper)
actor.SetProperty(prop)
renderer = vtk.vtkRenderer()
renderer.SetBackground(.045,.06,.09)
renderer.AddVolume(actor)
beam = vtk.vtkCylinderSource()
beam.SetRadius(.06)
beam.SetHeight(4.5)
beam.SetResolution(48)
beam_mapper = vtk.vtkPolyDataMapper()
beam_mapper.SetInputConnection(beam.GetOutputPort())
beam_actor = vtk.vtkActor()
beam_actor.SetMapper(beam_mapper)
beam_actor.RotateX(90)
beam_actor.SetScale(1,1,.65)
beam_actor.SetPosition(.25,0,0)
beam_actor.GetProperty().SetColor(.25,.9,1.)
beam_actor.GetProperty().SetOpacity(.35)
renderer.AddActor(beam_actor)
camera = renderer.GetActiveCamera()
camera.SetPosition(4,-6,3)
camera.SetFocalPoint(0,0,0)
camera.SetViewUp(0,0,1)
renderer.ResetCamera()
camera.Zoom(1.25)
window = vtk.vtkRenderWindow()
window.SetOffScreenRendering(1)
window.SetSize(1100,600)
window.AddRenderer(renderer)
window.Render()
capture = vtk.vtkWindowToImageFilter()
capture.SetInput(window)
capture.ReadFrontBufferOff()
capture.Update()
pixels = vtk_to_numpy(capture.GetOutput().GetPointData().GetScalars())
pixels = np.flipud(pixels.reshape(600,1100,-1))
q, phi, cake, iq = scattering(volume, spacing, origin)
with plt.style.context('dark_background'):
    fig = plt.figure(figsize=(11,9), layout='constrained')
    grid = fig.add_gridspec(2,2,height_ratios=[2,1])
    ax = fig.add_subplot(grid[0,:])
    ax.imshow(pixels)
    ax.axis('off')
    ax.set_title('SYNTHETIC DEMO — invented specimen and scattering', fontsize=14)
    ax = fig.add_subplot(grid[1,0])
    ax.plot(q, iq, color='#64dded')
    ax.set(xlabel='q (invented nm⁻¹)', ylabel='Mean intensity (a.u.)', title='Full-azimuth mean I(q)')
    ax = fig.add_subplot(grid[1,1])
    heat = ax.imshow(np.log10(cake), origin='lower', aspect='auto',
                     extent=[q[0],q[-1],-180,180], cmap='magma')
    ax.set(xlabel='q (invented nm⁻¹)', ylabel='φ (degrees)', title='Illustrative cake I(q, φ)')
    fig.colorbar(heat, ax=ax, label='log₁₀ intensity (a.u.)')
    fig.savefig(data_dir/'preview.png', dpi=140)
    plt.close(fig)
window.Finalize()
print(data_dir/'preview.png')
