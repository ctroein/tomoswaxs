const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
module.exports=async function checkSaxs(){
  const values={saxs_axes:[{x:[-10,-5,0,5],angle:[90,100,110]}],saxs_scan:0,saxs_row:1,saxs_column:1,
    saxs_link_ct:false};
  for(const key of ['x_origin','y_origin','x_offset','y_offset','angle_offset'])values[`saxs_map_${key}`]=0;
  for(const key of ['x_sign','y_sign'])values[`saxs_map_${key}`]=1;
  const listeners=[],calls=[];
  const state={addListener:fn=>listeners.push(fn),get:key=>values[key],set:(key,val)=>{values[key]=val;}};
  const window={trame:{state},nimUpdates:{submit:(...args)=>calls.push(args)}};
  vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../src/tomoswaxs/assets/saxs.js'),'utf8'),{window});
  const dirty=keys=>listeners[0]({type:'dirty-state',keys});
  assert.equal(values.saxs_input_x,-5);
  window.nimSaxs.position('x','4.8');
  assert.equal(calls.length,0,'Off-grid coordinates are rejected');
  assert.equal(values.saxs_input_x,-5);
  window.nimSaxs.position('x','5');
  assert.equal(calls.at(-1)[1].column,3);
  assert.equal(values.saxs_input_x,5,'A numeric selection snaps to an acquired position');
  dirty(['saxs_revision']);
  assert.equal(values.saxs_draft_column,3,'An older response leaves a newer request intact');
  values.saxs_column=3;dirty(['saxs_revision']);
  window.nimSaxs.edit('x');values.saxs_input_x='-9';
  dirty(['saxs_revision']);
  assert.equal(values.saxs_input_x,'-9','Responses preserve a number being typed');
  window.nimSaxs.position('x','-10');
  assert.equal(calls.at(-1)[1].column,0);
  window.nimSaxs.step('angle',1);
  assert.equal(calls.at(-1)[1].row,2);
  window.nimSaxs.step('angle',1);
  assert.equal(calls.at(-1)[1].row,2,'Stepping stops at the acquired end');
  const count=calls.length;
  window.nimSaxs.position('angle','');assert.equal(calls.length,count);
  values.saxs_map_x_origin='';window.nimSaxs.select();assert.equal(calls.length,count);
  values.saxs_column=2;dirty(['sample_context']);
  assert.equal(values.saxs_draft_column,2,'A sample-context change resets pending drafts');
  assert.equal(values.saxs_input_x,0);
  values.saxs_map_x_origin=0;
  values.saxs_axes[0].x_by_angle=[[-10,-5,0,5],[-9,-4,1,6],[-8,-3,2,7]];
  values.saxs_row=0;dirty(['sample_context']);
  assert.equal(values.saxs_input_x,0);
  window.nimSaxs.step('angle',1);
  assert.equal(values.saxs_input_x,1,'The X coordinate follows the selected mechanical angle');
  window.nimSaxs.position('x','6');
  assert.equal(calls.at(-1)[1].column,3);
  assert.equal(calls.at(-1)[1].placement.pivot_x,0);

  values.saxs_axes[0].x_by_angle=[[-10,-5,0,5],[-8,-3,2,7],[-5.8,-.8,4.2,9.2]];
  values.saxs_row=0;values.saxs_column=2;dirty(['sample_context']);
  window.nimSaxs.toggleXLock();
  assert.equal(values.saxs_lock_x,true);
  window.nimSaxs.step('angle',1);
  assert.equal(calls.at(-1)[1].column,2);
  assert.equal(values.saxs_input_x,2);
  // Simulate the angle slider, including its final change event.
  values.saxs_draft_row=2;window.nimSaxs.select();window.nimSaxs.select(true);
  assert.equal(calls.at(-1)[1].column,1,'Angle changes choose nearest X to the original target, without accumulating drift');
  assert.equal(values.saxs_input_x,-.8);
  window.nimSaxs.step('x',1);
  window.nimSaxs.step('angle',-1);
  assert.equal(calls.at(-1)[1].column,2,'Moving X establishes a new locked coordinate');
  window.nimSaxs.toggleXLock();window.nimSaxs.step('angle',-1);
  assert.equal(calls.at(-1)[1].column,2,'Unlocked angle changes preserve the measurement index');

  values.saxs_axes[0].x_by_angle[0][2]=1.23456789;
  values.saxs_column=2;values.saxs_row=0;dirty(['sample_context']);
  assert.equal(values.saxs_input_x,1.2346);
  window.nimSaxs.position('x','1.2346');
  assert.equal(calls.at(-1)[1].column,2,'Displayed rounded values can be accepted unchanged');
  assert.equal(values.saxs_axes[0].x_by_angle[0][2],1.23456789,'Rounding preserves measurement coordinates');
  values.saxs_map_x_offset=296.453440481;
  assert.equal(window.nimSaxs.formatCoordinate(values.saxs_map_x_offset),296.4534);
  assert.equal(values.saxs_map_x_offset,296.453440481,'Rendering a registration field preserves its full value');
  window.nimSaxs.placement('x_offset','297.4534');
  assert.equal(calls.at(-1)[1].placement.x_offset,297.4534);
  values.saxs_map_motors=[{name:'tab_x',reference:1.234567,x:1,y:0}];
  window.nimSaxs.motorPlacement('tab_x','reference','1.25');
  assert.equal(calls.at(-1)[1].placement.motors[0].reference,1.25);
};
if(require.main===module)module.exports().catch(error=>{console.error(error);process.exitCode=1;});
